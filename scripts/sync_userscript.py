#!/usr/bin/env python3
"""Embed the shared playback controller and synchronize the plain-text copy."""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BEGIN = '  // BEGIN SHARED PLAYBACK — generated by scripts/sync_userscript.py\n'
END = '  // END SHARED PLAYBACK'


def main():
    path = ROOT / 'youtube-chatgpt.user.js'
    source = path.read_text(encoding='utf-8')
    if source.count(BEGIN) != 1 or source.count(END) != 1:
        raise ValueError('Expected exactly one shared playback region')
    before, rest = source.split(BEGIN)
    _, after = rest.split(END)
    shared = (ROOT / 'extension' / 'playback.js').read_text(encoding='utf-8').rstrip()
    embedded = '\n'.join('  ' + line if line else '' for line in shared.splitlines())
    source = before + BEGIN + embedded + '\n' + END + after
    path.write_text(source, encoding='utf-8')
    (ROOT / 'youtube-chatgpt.txt').write_text(source, encoding='utf-8')
    print('Shared playback and userscript text copy synchronized.')


if __name__ == '__main__':
    main()
